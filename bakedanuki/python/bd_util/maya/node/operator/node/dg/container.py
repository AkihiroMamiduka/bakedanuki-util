    ctrt = customTreatment

    creator = DataStringField()
    ctor = creator

    creationDate = DataStringField()
    cdat = creationDate

    containerType = DataStringField()
    ctyp = containerType

    rootTransform = MessageField()
    rt = rootTransform

    isHierarchicalRoot = BoolField(default_value=False)
    ihr = isHierarchicalRoot
