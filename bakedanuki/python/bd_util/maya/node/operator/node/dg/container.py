class Container(DG):
    __slots__ = ()

    NODE_TYPE = "container"

    hyperLayout = MessageField()
    hl = hyperLayout

    isCollapsed = BoolField(default_value=False)
    isc = isCollapsed

    blackBox = BoolField(default_value=False)
    bbx = blackBox

    rmbCommand = DataStringField()
    rmc = rmbCommand

    templateName = DataStringField()
